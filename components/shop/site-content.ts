// Щоб змінити текст — редагуй потрібну сторінку нижче.
// Щоб додати нову сторінку — додай новий об'єкт у масив `sitePages`
//   і додай посилання у футер (components/shop/footer.tsx).
//
// Кожна секція (`section`) має:
//   - heading:  заголовок секції (необов'язково)
//   - blocks:   абзаци тексту та/або марковані списки
//   - card:     true → секція в рамці (для контактів тощо)
//   - contacts: блок контактів з іконками (адреса, email, телефон)
// ─────────────────────────────────────────────────────────────────────────────

export type ContentBlock =
  | { type: "paragraph"; text: string }
  | { type: "list"; items: string[] }

export type ContactInfo = {
  address?: string[]
  email?: string
  phone?: string
  phoneHref?: string
}

export type ContentSection = {
  heading?: string
  blocks?: ContentBlock[]
  card?: boolean
  contacts?: ContactInfo
}

export type SitePage = {
  /** Частина URL, напр. "returns" → /returns */
  slug: string
  /** Напис у футері */
  navLabel: string
  /** Великий заголовок угорі сторінки */
  title: string
  /** SEO: заголовок вкладки браузера */
  metaTitle: string
  /** SEO: опис для пошукових систем */
  metaDescription: string
  sections: ContentSection[]
}

